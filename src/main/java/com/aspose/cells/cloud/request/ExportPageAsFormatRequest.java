package com.aspose.cells.cloud.request;

import com.aspose.cells.cloud.RequestOption;
import com.aspose.cells.cloud.UrlUtils;
import java.util.HashMap;
import java.util.LinkedHashMap;
import java.util.Map;

public class ExportPageAsFormatRequest implements RequestOption {

    private String format;
    private Integer index;
    private String name;
    private String worksheet;
    private Boolean autoColumnsFit;
    private Boolean autoRowsFit;
    private String folder;
    private String fontsLocation;
    private String outPath;
    private String outStorageName;
    private String password;
    private String region;
    private String storageName;

    private HashMap<String, String> extendQueryParameterMap;

    public ExportPageAsFormatRequest(String format, Integer index, String name, String worksheet) {
        this.format = format;
        this.index = index;
        this.name = name;
        this.worksheet = worksheet;
    }

    public String getFormat() {
        return format;
    }

    public Integer getIndex() {
        return index;
    }

    public String getName() {
        return name;
    }

    public String getWorksheet() {
        return worksheet;
    }

    public Boolean getAutoColumnsFit() {
        return autoColumnsFit;
    }

    public void setAutoColumnsFit(Boolean autoColumnsFit) {
        this.autoColumnsFit = autoColumnsFit;
    }

    public Boolean getAutoRowsFit() {
        return autoRowsFit;
    }

    public void setAutoRowsFit(Boolean autoRowsFit) {
        this.autoRowsFit = autoRowsFit;
    }

    public String getFolder() {
        return folder;
    }

    public void setFolder(String folder) {
        this.folder = folder;
    }

    public String getFontsLocation() {
        return fontsLocation;
    }

    public void setFontsLocation(String fontsLocation) {
        this.fontsLocation = fontsLocation;
    }

    public String getOutPath() {
        return outPath;
    }

    public void setOutPath(String outPath) {
        this.outPath = outPath;
    }

    public String getOutStorageName() {
        return outStorageName;
    }

    public void setOutStorageName(String outStorageName) {
        this.outStorageName = outStorageName;
    }

    public String getPassword() {
        return password;
    }

    public void setPassword(String password) {
        this.password = password;
    }

    public String getRegion() {
        return region;
    }

    public void setRegion(String region) {
        this.region = region;
    }

    public String getStorageName() {
        return storageName;
    }

    public void setStorageName(String storageName) {
        this.storageName = storageName;
    }

    public HashMap<String, String> getExtendQueryParameterMap() {
        return extendQueryParameterMap;
    }

    public void setExtendQueryParameterMap(HashMap<String, String> extendQueryParameterMap) {
        this.extendQueryParameterMap = extendQueryParameterMap;
    }

    public ExportPageAsFormatRequest addQueryParameter(String key, String value) {
        if (this.extendQueryParameterMap == null) {
            this.extendQueryParameterMap = new HashMap<String, String>();
        }
        this.extendQueryParameterMap.put(key, value);
        return this;
    }

    @Override
    public String getMethod() {
        return "GET";
    }

    @Override
    public String getApiVersion() {
        return "v4.0";
    }

    @Override
    public String getPath() {
        String path = "/cells/{name}/worksheets/{worksheet}/pages/{index}";
        path = path.replace("{name}", UrlUtils.urlEncode(this.name == null ? "" : String.valueOf(this.name)));
        path = path.replace("{worksheet}", UrlUtils.urlEncode(this.worksheet == null ? "" : String.valueOf(this.worksheet)));
        path = path.replace("{index}", UrlUtils.urlEncode(this.index == null ? "" : String.valueOf(this.index)));
        return path;
    }

    @Override
    public Map<String, String> getQueryParameters() {
        Map<String, String> query = new LinkedHashMap<String, String>();
        query.put("format", this.format == null ? "" : this.format);
        if (this.folder != null && !this.folder.isEmpty()) {
            query.put("folder", this.folder);
        }
        if (this.storageName != null && !this.storageName.isEmpty()) {
            query.put("storageName", this.storageName);
        }
        if (this.outPath != null && !this.outPath.isEmpty()) {
            query.put("outPath", this.outPath);
        }
        if (this.outStorageName != null && !this.outStorageName.isEmpty()) {
            query.put("outStorageName", this.outStorageName);
        }
        if (this.fontsLocation != null && !this.fontsLocation.isEmpty()) {
            query.put("fontsLocation", this.fontsLocation);
        }
        if (this.autoRowsFit != null) {
            query.put("AutoRowsFit", String.valueOf(this.autoRowsFit));
        }
        if (this.autoColumnsFit != null) {
            query.put("AutoColumnsFit", String.valueOf(this.autoColumnsFit));
        }
        if (this.region != null && !this.region.isEmpty()) {
            query.put("region", this.region);
        }
        if (this.password != null && !this.password.isEmpty()) {
            query.put("password", this.password);
        }
        if (this.extendQueryParameterMap != null) {
            query.putAll(this.extendQueryParameterMap);
        }
        return query;
    }

    @Override
    public Map<String, String> getHeaderParameters() {
        Map<String, String> headers = new LinkedHashMap<String, String>();
        headers.put("Content-Type", "application/json");
        return headers;
    }

    @Override
    public Object getJsonBody() {
        return null;
    }

    @Override
    public Map<String, Object> getMultipartForm() {
        return null;
    }

    @Override
    public boolean isBinaryResponse() {
        return true;
    }
}
