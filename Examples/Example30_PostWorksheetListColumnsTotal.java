package com.aspose.cells.cloud.examples;

import com.aspose.cells.cloud.*;
import com.aspose.cells.cloud.model.*;
import com.aspose.cells.cloud.request.*;
import java.io.File;
import java.util.*;

/** Migrated from the legacy Java examples. */
public final class Example30_PostWorksheetListColumnsTotal {

    public static void main(String[] args) {
        CellsCloudClient client = new CellsCloudClient(
                System.getenv("CellsCloudClientId"),
                System.getenv("CellsCloudClientSecret"),
                System.getenv("CellsCloudApiBaseUrl"));
        new Example30_PostWorksheetListColumnsTotal().run(client);
    }

    public void run(CellsCloudClient client) {

        try{
            String remoteFolder = "TestData/In";

            String localName = "Book1.xlsx";
            String remoteName = "Book1.xlsx";

            client.call(new UploadFileRequest(
                    remoteFolder + "/" + remoteName, FormFile.ofPath(localName)));

            ArrayList<TableTotalRequest> tableTotalRequests = new ArrayList<TableTotalRequest>();
            TableTotalRequest tableTotalRequest = new TableTotalRequest();
            tableTotalRequest.setListColumnIndex(1);

            tableTotalRequest.setTotalsCalculation("Average");

            tableTotalRequests.add(tableTotalRequest);

            PostWorksheetListColumnsTotalRequest request = new PostWorksheetListColumnsTotalRequest(0, remoteName, "Sheet7", tableTotalRequests);
            request.setFolder(remoteFolder);
            request.setStorageName("");
            client.call(request);

        } catch (ApiException e) {
            // TODO Auto-generated catch block
            e.printStackTrace();
        }		
    
    }
}
